func TestExactOwnedArtifactRemovalRefusesConcurrentOriginalReplacement_SW2_PKG_001(t *testing.T) {
	parent, directoryName, uid, gid := newOwnedArtifactRemovalFixture(t)
	content := []byte("managed\n")
	expectation := exactContentExpectation("test generated artifact", "managed.conf", content, 0600)
	directory := filepath.Join(parent, directoryName)
	path := filepath.Join(directory, expectation.name)
	writeOwnedArtifactFixture(t, path, content, 0600)

	options := defaultExactOwnedArtifactRemovalOptions()
	options.warn = func(string) {}
	originalRename := options.renameat2
	exchangeCalls := 0
	options.renameat2 = func(oldDirectory int, oldName string, newDirectory int, newName string, flags uint) error {
		if flags == unix.RENAME_EXCHANGE {
			exchangeCalls++
		}
		return originalRename(oldDirectory, oldName, newDirectory, newName, flags)
	}
	replaced := false
	options.faultPoint = func(point string) {
		if point == "after-rename:"+expectation.name && !replaced {
			replaced = true
			writeOwnedArtifactFixture(t, path, []byte("operator\n"), 0600)
		}
	}
	removed, err := removeExactOwnedArtifactAtUsing(
		parent,
		directoryName,
		uid,
		gid,
		expectation,
		options,
	)
	if err == nil || removed || !strings.Contains(err.Error(), "appeared concurrently") {
		t.Fatalf("concurrent replacement result = %t, %v", removed, err)
	}
	if got, readErr := os.ReadFile(path); readErr != nil || string(got) != "operator\n" { // #nosec G304 -- path is confined to the private concurrent-replacement fixture root
		t.Fatalf("concurrent replacement = %q, %v", got, readErr)
	}
	if exchangeCalls != 0 {
		t.Fatalf("concurrent replacement was displaced by %d exchange operations", exchangeCalls)
	}
	entries, readErr := os.ReadDir(directory)
	if readErr != nil {
		t.Fatal(readErr)
	}
	quarantines := 0
	preserved := 0
	for _, entry := range entries {
		if strings.Contains(entry.Name(), ".syswarden-removal-") {
			quarantines++
		}
		if strings.Contains(entry.Name(), ".syswarden-preserved-") {
			preserved++
			got, err := os.ReadFile(filepath.Join(directory, entry.Name())) // #nosec G304 -- entry came from ReadDir on the private quarantine fixture
			if err != nil || !bytes.Equal(got, content) {
				t.Fatalf("preserved exact bytes = %q, %v", got, err)
			}
		}
	}
	if quarantines != 1 || preserved != 0 {
		t.Fatalf("recoverable quarantine / extra preservation count = %d/%d, want 1/0", quarantines, preserved)
	}
}

