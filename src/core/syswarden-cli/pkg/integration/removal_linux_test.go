func newOwnedArtifactRemovalFixture(t *testing.T) (string, string, uint32, uint32) {
	t.Helper()
	parent := t.TempDir()
	directoryName := "managed.d"
	directory := filepath.Join(parent, directoryName)
	if err := os.Mkdir(directory, 0750); err != nil {
		t.Fatalf("create managed fixture directory: %v", err)
	}
	info, err := os.Stat(parent)
	if err != nil {
		t.Fatalf("stat managed fixture parent: %v", err)
	}
	stat, ok := info.Sys().(*syscall.Stat_t)
	if !ok {
		t.Fatal("managed fixture parent has no Linux stat metadata")
	}
	return parent, directoryName, stat.Uid, stat.Gid
}

func writeOwnedArtifactFixture(t *testing.T, path string, content []byte, mode os.FileMode) {
	t.Helper()
	if err := os.WriteFile(path, content, mode); err != nil {
		t.Fatalf("write managed artifact fixture: %v", err)
	}
	if err := os.Chmod(path, mode); err != nil {
		t.Fatalf("set managed artifact fixture mode: %v", err)
	}
}

func quietOwnedArtifactRemovalOptions(warnings *[]string) exactOwnedArtifactRemovalOptions {
	options := defaultExactOwnedArtifactRemovalOptions()
	options.warn = func(message string) {
		*warnings = append(*warnings, message)
	}
	return options
}

func TestExactOwnedArtifactRemovalQuarantinesReattestsAndUnlinks_SW2_PKG_001(t *testing.T) {
	parent, directoryName, uid, gid := newOwnedArtifactRemovalFixture(t)
	content := []byte("exact generated bytes\n")
	expectation := exactContentExpectation("test generated artifact", "managed.conf", content, 0600)
	path := filepath.Join(parent, directoryName, expectation.name)
	writeOwnedArtifactFixture(t, path, content, 0600)

	warnings := []string{}
	options := quietOwnedArtifactRemovalOptions(&warnings)
	syncCalls := 0
	originalSync := options.syncDirectory
	options.syncDirectory = func(directory *os.File) error {
		syncCalls++
		return originalSync(directory)
	}
	removed, err := removeExactOwnedArtifactAtUsing(
		parent,
		directoryName,
		uid,
		gid,
		expectation,
		options,
	)
	if err != nil || !removed {
		t.Fatalf("exact removal = %t, %v", removed, err)
	}
	if len(warnings) != 0 {
		t.Fatalf("exact removal warnings = %v", warnings)
	}
	if syncCalls != 2 {
		t.Fatalf("directory sync calls = %d, want rename and unlink durability", syncCalls)
	}
	if _, err := os.Lstat(path); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("exact artifact remains: %v", err)
	}
	entries, err := os.ReadDir(filepath.Dir(path))
	if err != nil {
		t.Fatalf("read managed directory after removal: %v", err)
	}
	for _, entry := range entries {
		if strings.Contains(entry.Name(), ".syswarden-removal-") {
			t.Fatalf("quarantine remains after exact removal: %s", entry.Name())
		}
	}
}

